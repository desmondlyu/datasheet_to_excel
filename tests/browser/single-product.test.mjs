import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as pdfjs from 'pdfjs-dist/legacy/build/pdf.mjs';
import {parsePdf} from '../../browser/pdf-parser.mjs';
const path=process.env.SPEC_SINGLE_REFERENCE_PDF;
test('single-product byte-layout PDF extracts commands and excludes package pages',{skip:!path,timeout:120000},async()=>{
 const r=await parsePdf(pdfjs,await readFile(path));
 assert.deepEqual(r.products,['W25Q33PW']);
 assert.equal(r.rows.length,79);
 assert.equal(r.rows.find(x=>x.parameter.includes('Standby Mode without ID')).symbol,'tRES1');
 assert.ok(r.sources.some(s=>s.pdf_page===25&&s.text.includes('P6')));
 assert.ok(r.sources.every(s=>s.pdf_page<94));
 assert.deepEqual(r.command_pages,[21,22,23,24]);
 assert.ok(!r.review.some(s=>s.section.startsWith('指令表')));
 const pp=r.commands.filter(c=>c.command==='Page Program');
 assert.deepEqual(pp.map(c=>[c.opcode,c.mode,c.address]),[['02h','1-1-1','A23-A16, A15-A8, A7-A0'],['02h','4-4-4','A23-A16, A15-A8, A7-A0']]);
 const tpp=r.rows.find(x=>x.symbol==='tPP');
 assert.equal(tpp.typ,.2);assert.equal(tpp.max,1.2);assert.match(tpp._commands,/02h Page Program/);assert.match(tpp._commands,/32h Quad Input Page Program/);
 assert.equal(r.rows.filter(x=>x['spec type']==='DC').length,19);
 assert.equal(r.rows.find(x=>x.symbol==='tCE').max,40);
 assert.ok(r.commands.some(c=>c.opcode==='EDh'&&c.mode==='1-4d-4d'&&c.dummy.includes('11')));
});
